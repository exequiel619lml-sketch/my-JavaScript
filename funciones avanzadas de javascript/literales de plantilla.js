// Definimos dos variables con texto
let greet = "Hello";
let place = "World";

// Usamos `${}` para combinar las variables en un solo mensaje
console.log(`${greet} ${place}!`); // Esto mostrará: Hello World!

// Usamos `${}` para evaluar una expresión matemática dentro del texto
console.log(`${1 + 1 + 1 + 1 + 1} stars!`); // Esto mostrará: 5 stars!